// THE VOICE — speaks every phrase in lyrics.js once (ElevenLabs text-to-speech with character timestamps),
// keeps the audio in assets/vo/ and writes voice-data.js: for each phrase its length and the time of every word.
// score.js places the phrases on bars from that file, so the captions, the animals and the sound share one timeline.
//   node tools/voice.js          (cached: only phrases that are not in assets/vo/ are requested)
// The API key is injected by the session's proxy; outside it, set ELEVENLABS_API_KEY.
const fs = require('fs');
const path = require('path');
const crypto = require('crypto');
const { execFileSync } = require('child_process');
const L = require('../lyrics');

const ROOT = path.join(__dirname, '..');
const DIR = path.join(ROOT, 'assets', 'vo');
fs.mkdirSync(DIR, { recursive: true });
const VOICE = 'cgSgspJ2msm6clMCkdW9'; // a premade, playful and warm voice
const MODEL = 'eleven_multilingual_v2';
const MODES = {
  song: { stability: 0.45, similarity_boost: 0.8, style: 0.45, use_speaker_boost: true },
  soft: { stability: 0.75, similarity_boost: 0.8, style: 0.15, use_speaker_boost: true, speed: 0.85 },
  sfx: { stability: 0.35, similarity_boost: 0.8, style: 0.7, use_speaker_boost: true },
};
const keyOf = (text, mode) => `${mode}:${text}`;
const fileOf = (text, mode) => crypto.createHash('sha1').update(keyOf(text, mode)).digest('hex').slice(0, 12);

// ---------- every phrase the week needs, with the phrase after it (for natural phrasing) ----------
const want = new Map();
const add = (list, mode) => list.forEach((text, i) => {
  if (!text || text === 'boing') return;
  const k = keyOf(text, mode);
  if (!want.has(k)) want.set(k, { text, mode, next: list[i + 1] || '' });
});
for (const a of Object.values(L.ANIMALS)) { add(a.verse, 'song'); add(a.chorus, 'song'); add([a.sound], 'sfx'); }
add(L.FINAL, 'song');
add(L.SLEEPY, 'soft');
for (const s of L.LULLABY) add(s.lines, 'soft');

// curl, because it follows the session's HTTPS proxy (Node's fetch does not)
function speak(p) {
  const body = JSON.stringify({ text: p.text, model_id: MODEL, voice_settings: MODES[p.mode], seed: 7, ...(p.mode !== 'sfx' && p.next ? { next_text: p.next } : {}) });
  const out = execFileSync('curl', ['-sS', '-m', '90', '--fail-with-body', '-X', 'POST',
    `https://api.elevenlabs.io/v1/text-to-speech/${VOICE}/with-timestamps?output_format=mp3_44100_128`,
    '-H', `xi-api-key: ${process.env.ELEVENLABS_API_KEY || 'proxy'}`, '-H', 'Content-Type: application/json', '-d', body], { maxBuffer: 64 << 20 });
  return JSON.parse(out.toString());
}

function words(al) {
  const out = [];
  let cur = null;
  al.characters.forEach((ch, i) => {
    if (/\s/.test(ch)) { cur = null; return; }
    if (!cur) { cur = { w: '', t: al.character_start_times_seconds[i], end: 0 }; out.push(cur); }
    cur.w += ch; cur.end = al.character_end_times_seconds[i];
  });
  return out.map((w) => ({ w: w.w, t: +w.t.toFixed(3), end: +w.end.toFixed(3) }));
}
const duration = (f) => parseFloat(execFileSync('ffprobe', ['-v', 'error', '-show_entries', 'format=duration', '-of', 'csv=p=0', f]).toString());

(async () => {
  const data = {};
  let made = 0, chars = 0;
  for (const [k, p] of want) {
    const id = fileOf(p.text, p.mode);
    const mp3 = path.join(DIR, id + '.mp3'), meta = path.join(DIR, id + '.json');
    if (!fs.existsSync(mp3) || !fs.existsSync(meta)) {
      const j = speak(p);
      fs.writeFileSync(mp3, Buffer.from(j.audio_base64, 'base64'));
      fs.writeFileSync(meta, JSON.stringify({ text: p.text, mode: p.mode, words: words(j.alignment) }));
      made++; chars += p.text.length;
      console.log(`  spoke  ${k}`);
    }
    const m = JSON.parse(fs.readFileSync(meta, 'utf8'));
    data[k] = { file: `assets/vo/${id}.mp3`, dur: +duration(mp3).toFixed(3), words: m.words };
  }
  const js = `// generated by tools/voice.js: the length and word times of every spoken phrase\n(function () {\n  const VOICE = ${JSON.stringify(data, null, 1)};\n  if (typeof module !== 'undefined') module.exports = VOICE; else globalThis.VOICE = VOICE;\n})();\n`;
  fs.writeFileSync(path.join(ROOT, 'voice-data.js'), js);
  console.log(`voice-data.js: ${want.size} phrases (${made} new, ${chars} characters requested)`);
})().catch((e) => { console.error(String(e.message || e)); process.exit(1); });
